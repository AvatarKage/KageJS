import { AdvancedError, assert } from "@kagejs/utilities";

import type { Automod } from "../../types/automod.type.js";
import type { Severity } from "../../types/common.type.js";
import type { FilterConfig, FilterMatch } from "../../types/filter.type.js";
import toRegex from "../helpers/toRegex.js";

/**
 * Represents an individual automod filter.
 *
 * Handles blacklist and whitelist pattern management, message normalization,
 * obfuscation detection, capitalization normalization, reversed-text detection,
 * and match generation.
 *
 * A Filter instance inherits default configuration values from its associated
 * Automod instance while allowing individual filter settings to override them.
 *
 * @remarks
 * Blacklist entries define patterns that should trigger matches.
 * Whitelist entries define patterns that suppress matches when the matched
 * range is fully contained within a whitelisted range.
 *
 * Supports both string wildcard patterns and native RegExp instances.
 *
 * @example
 * const filter = new Filter(config, automod);
 *
 * const matches = filter.test("Example message");
 */
export default class Filter {
    /**
     * Unique identifier of the filter.
     *
     * @type {string}
     */
    public id: string;

    /**
     * Optional display name of the filter.
     *
     * @type {string | undefined}
     */
    public name?: string;

    /**
     * Optional group identifier associated with the filter.
     *
     * Defaults to the group configured on the parent Automod instance
     * when not explicitly provided.
     *
     * @type {string | undefined}
     */
    public group?: string;

    /**
     * Determines whether the filter is enabled.
     *
     * When disabled, {@link test} returns an empty array without
     * evaluating the message.
     *
     * Defaults to the parent Automod instance's enabled setting.
     *
     * @type {boolean | undefined}
     */
    public enabled: boolean;

    /**
     * Determines whether all configured conditions must match.
     *
     * Defaults to the parent Automod instance's matchAll setting.
     *
     * @type {boolean | undefined}
     */
    public matchAll: boolean;

    /**
     * Severity level assigned to matches generated by this filter.
     *
     * Defaults to the parent Automod instance's severity setting.
     *
     * @type {Severity}
     */
    public severity: Severity;

    /**
     * Optional response associated with matches generated by this filter.
     *
     * Can be used by the automoderation system to determine the
     * appropriate response to a detected message.
     *
     * @type {string | undefined}
     */
    public response?: string;

    /**
     * Controls which message normalization and detection behaviors
     * should be ignored by associated filters.
     *
     * Individual filters inherit this configuration unless they
     * provide their own ignore settings.
     *
     * @property {boolean} [obfuscation] - Disables obfuscation normalization.
     * @property {boolean} [capitalization] - Disables capitalization normalization.
     * @property {boolean} [reversed] - Disables reversed-text detection.
     * @property {boolean} [spacing] - Disables advanced spacing detection.
     *
     * @type {{
     *     obfuscation?: boolean;
     *     capitalization?: boolean;
     *     reversed?: boolean;
     *     spacing?: boolean;
     * } | undefined}
     */
    public ignore: {
        obfuscation: boolean;
        capitalization: boolean;
        reversed: boolean;
        spacing: boolean;
    };

    /**
     * Stores blacklist patterns and their compiled regular expressions.
     *
     * The original pattern is used as the Map key, while the associated
     * RegExp is used for matching.
     *
     * String patterns are converted using {@link toRegex}.
     *
     * @private
     * @type {Map<string | RegExp, RegExp>}
     */
    private blacklist: Map<string | RegExp, RegExp> = new Map();

    /**
     * Stores whitelist patterns and their compiled regular expressions.
     *
     * Whitelist matches are used to suppress blacklist matches when
     * the blacklist match range is fully contained within a whitelist
     * match range.
     *
     * @private
     * @type {Map<string | RegExp, RegExp>}
     */
    private whitelist: Map<string | RegExp, RegExp> = new Map();

    /**
     * Automod instance associated with this filter.
     *
     * Provides inherited configuration and optional message
     * normalization functionality.
     *
     * @private
     * @type {Automod}
     */
    private automod: Automod;

    /**
     * Creates a Filter instance using the supplied configuration
     * and parent Automod instance.
     *
     * Initializes filter properties using the provided configuration,
     * falling back to the corresponding Automod settings when values
     * are not explicitly supplied.
     *
     * Also registers the initial blacklist and whitelist entries.
     *
     * @param config - Filter configuration containing its identifier,
     * settings, blacklist patterns, and whitelist patterns.
     *
     * @param automod - Parent Automod instance providing inherited
     * configuration and normalization functionality.
     *
     * @example
     * const filter = new Filter(filterConfig, automod);
     *
     * @remarks
     * Configuration inheritance:
     * - `group` falls back to `automod.group`.
     * - `enabled` falls back to `automod.enabled`.
     * - `matchAll` falls back to `automod.matchAll`.
     * - `severity` falls back to `automod.severity`.
     * - `response` falls back to `automod.response`.
     * - `ignore` falls back to `automod.ignore`.
     *
     * Blacklist and whitelist entries are registered through
     * {@link addBlacklist} and {@link addWhitelist}.
     */
    constructor(config: FilterConfig, automod: Automod) {
        this.automod = automod;

        this.id = config.id;
        this.name = config.name;
        this.group = config.group ?? automod.group;

        this.enabled = config.enabled ?? automod.enabled;
        this.matchAll = config.matchAll ?? automod.matchAll;

        this.severity = config.severity ?? automod.severity;
        this.response = config.response ?? automod.response;

        this.ignore = {
            obfuscation: config.ignore?.obfuscation ?? automod.ignore?.obfuscation,
            capitalization: config.ignore?.capitalization ?? automod.ignore?.capitalization,
            reversed: config.ignore?.reversed ?? automod.ignore?.reversed,
            spacing: config.ignore?.spacing ?? automod.ignore?.spacing,
        };

        for (const value of config.blacklist ?? []) {
            this.addBlacklist(value);
        }

        for (const value of config.whitelist ?? []) {
            this.addWhitelist(value);
        }
    }

    /**
     * Adds a pattern to the filter's blacklist.
     *
     * String patterns are converted into regular expressions using
     * {@link toRegex}. Existing RegExp instances are stored directly.
     *
     * If the same pattern key already exists, its associated RegExp
     * is replaced.
     *
     * @param value - Wildcard string pattern or RegExp instance
     * representing content that should trigger a match.
     *
     * @returns {void}
     *
     * @example
     * filter.addBlacklist("spam");
     *
     * @example
     * // Wildcard pattern.
     * filter.addBlacklist("*advertisement*");
     *
     * @example
     * // Native regular expression.
     * filter.addBlacklist(/spam|scam/gi);
     */
    public addBlacklist(value: string | RegExp): void {
        const regex = value instanceof RegExp ? value : toRegex(value, !this.ignore.spacing);
        this.blacklist.set(value, regex);
    }

    /**
     * Adds a pattern to the filter's whitelist.
     *
     * String patterns are converted into regular expressions using
     * {@link toRegex}. Existing RegExp instances are stored directly.
     *
     * Whitelist matches suppress blacklist matches when the complete
     * blacklist match range is contained within a whitelist match range.
     *
     * If the same pattern key already exists, its associated RegExp
     * is replaced.
     *
     * @param value - Wildcard string pattern or RegExp instance
     * representing content that should be exempt from matching.
     *
     * @returns {void}
     *
     * @example
     * filter.addWhitelist("trusted");
     *
     * @example
     * // Wildcard whitelist pattern.
     * filter.addWhitelist("*approved*");
     *
     * @example
     * // Native regular expression.
     * filter.addWhitelist(/safe|trusted/gi);
     */
    public addWhitelist(value: string | RegExp): void {
        const regex = value instanceof RegExp ? value : toRegex(value, !this.ignore.spacing);
        this.whitelist.set(value, regex);
    }

    /**
     * Removes a pattern from the filter's blacklist.
     *
     * Deletes the entry associated with the supplied pattern key.
     *
     * @param value - Original string pattern or RegExp instance
     * used when the blacklist entry was registered.
     *
     * @returns {void}
     *
     * @remarks
     * The supplied value must match the original Map key.
     * A different RegExp instance with identical source and flags
     * will not remove the existing entry.
     *
     * @example
     * filter.removeBlacklist("spam");
     */
    public removeBlacklist(value: string | RegExp): void {
        this.blacklist.delete(value);
    }

    /**
     * Removes a pattern from the filter's whitelist.
     *
     * Deletes the entry associated with the supplied pattern key.
     *
     * @param value - Original string pattern or RegExp instance
     * used when the whitelist entry was registered.
     *
     * @returns {void}
     *
     * @remarks
     * The supplied value must match the original Map key.
     * A different RegExp instance with identical source and flags
     * will not remove the existing entry.
     *
     * @example
     * filter.removeWhitelist("trusted");
     */
    public removeWhitelist(value: string | RegExp): void {
        this.whitelist.delete(value);
    }

    /**
     * Generates normalized variants of a message.
     *
     * Applies the configured normalization transformations according
     * to the filter's ignore settings.
     *
     * Supported transformations:
     * - Obfuscation normalization through `automod.normalize`.
     * - Lowercase conversion for capitalization normalization.
     * - Duplicate variant elimination.
     *
     * @private
     *
     * @param message - Message content to normalize.
     *
     * @returns An array of unique normalized message variants.
     *
     * @throws {AdvancedError} Error code `1101` when the configured
     * Automod normalization function throws an error.
     *
     * @remarks
     * Obfuscation normalization is skipped when
     * `ignore.obfuscation` is `true` or when `automod.normalize`
     * is not a function.
     *
     * Capitalization normalization is skipped when
     * `ignore.capitalization` is `true`.
     *
     * @example
     * // Internal method.
     * // Generates normalized variants for message evaluation.
     */
    private normalize(message: string): string[] {
        let variants = [message];

        if (
            !this.ignore?.obfuscation &&
            assert(this.automod.normalize).isFunction()
        ) {
            try {
                variants = this.automod.normalize(message);
            } catch (error) {
                throw new AdvancedError(1101, {
                    message: String(error),
                    details: { message }
                });
            }
        }

        if (!this.ignore?.capitalization) {
            variants = variants.map(value => value.toLowerCase());
        }

        return [...new Set(variants)];
    }

    /**
     * Reverses a message while preserving Unicode code points.
     *
     * Uses the spread operator to convert the string into an iterable
     * sequence before reversing its elements.
     *
     * @private
     *
     * @param message - String to reverse.
     *
     * @returns The reversed string.
     *
     * @example
     * // Internal method.
     * // "hello" becomes "olleh".
     */
    private reverse(message: string): string {
        return [...message].reverse().join("");
    }

    /**
     * Tests a message against the filter's blacklist and whitelist.
     *
     * Evaluates the message using configured patterns and enabled
     * normalization strategies, producing detailed FilterMatch results.
     *
     * Detection supports:
     * - Direct blacklist matching.
     * - Normalized and obfuscated message matching.
     * - Case-insensitive matching through normalization.
     * - Reversed-text matching for string blacklist patterns.
     * - Whitelist-based match suppression.
     * - Duplicate match elimination.
     *
     * @param message - Original message content to evaluate.
     *
     * @returns An array of FilterMatch objects describing detected
     * blacklist matches.
     *
     * Returns an empty array when the filter is disabled or when
     * no valid matches are detected.
     *
     * @throws {AdvancedError} Error code `1101` when Automod
     * normalization fails during message evaluation.
     *
     * @remarks
     * Message preprocessing:
     * - Removes zero-width characters.
     * - Replaces consecutive whitespace with a single space.
     * - Trims leading and trailing whitespace.
     *
     * Matching behavior:
     * - RegExp blacklist entries are checked against the original
     * message and normalized variants.
     * - String blacklist entries are checked against normalized
     * variants, reversed normalized variants, and the original message.
     * - Reversed matching is disabled when `ignore.reversed` is `true`.
     * - Whitelist matches suppress blacklist matches only when the
     * blacklist match range is fully contained within a whitelist range.
     *
     * Returned matches contain:
     * - `filter`: Filter identification metadata.
     * - `regex`: Regular expression responsible for the match.
     * - `match.raw`: Corresponding original message text.
     * - `match.normalized`: Matched normalized representation.
     * - `severity`: Configured filter severity.
     * - `response`: Configured response, when available.
     *
     * @example
     * const matches = filter.test("Example message");
     *
     * @example
     * // Check whether the filter detected any matches.
     * const detected = filter.test("Example message").length > 0;
     *
     * @example
     * // Process detailed match information.
     * for (const match of filter.test("Example message")) {
     *     console.log(match.match.raw);
     *     console.log(match.severity);
     * }
     */
    public test(message: string): FilterMatch[] {
        if (!this.enabled) {
            return [];
        }

        const matches: FilterMatch[] = [];

        const cleanedMessage = message
            .replace(/[\u200B-\u200D\uFEFF]/g, "")
            .replace(/\s+/g, " ")
            .trim();

        const normalizedVariants = this.normalize(cleanedMessage);

        const getMatches = (
            target: string,
            regex: RegExp
        ): RegExpExecArray[] => {
            const flags = regex.flags.replace(/[gy]/g, "") + "g";
            const matcher = new RegExp(regex.source, flags);
            const results: RegExpExecArray[] = [];

            let match: RegExpExecArray | null;

            while ((match = matcher.exec(target)) !== null) {
                results.push(match);

                if (match[0].length === 0) {
                    matcher.lastIndex++;
                }
            }

            return results;
        };

        const findOriginalRange = (
            target: string,
            normalizedMatch: string
        ): { start: number; end: number } | null => {
            for (let start = 0; start < target.length; start++) {
                for (let end = start + 1; end <= target.length; end++) {
                    const candidate = target.slice(start, end);

                    if (this.normalize(candidate).includes(normalizedMatch)) {
                        return { start, end };
                    }
                }
            }

            return null;
        };

        const whitelistRanges = [...this.whitelist.values()].flatMap(regex =>
            getMatches(message, regex).map(match => ({
                start: match.index,
                end: match.index + match[0].length
            }))
        );

        const addMatch = (
            regex: RegExp,
            raw: string,
            normalized: string,
            range: { start: number; end: number }
        ): void => {
            const isWhitelisted = whitelistRanges.some(
                whitelist =>
                    whitelist.start <= range.start &&
                    whitelist.end >= range.end
            );

            if (isWhitelisted) {
                return;
            }

            const duplicate = matches.some(
                existing =>
                    existing.regex.source === regex.source &&
                    existing.match.raw === raw &&
                    existing.match.normalized === normalized
            );

            if (duplicate) {
                return;
            }

            matches.push({
                filter: {
                    id: this.id,
                    name: this.name,
                    group: this.group
                },
                regex,
                match: {
                    raw,
                    normalized
                },
                severity: this.severity,
                response: this.response
            });
        };

        for (const [value, regex] of this.blacklist) {
            if (value instanceof RegExp) {
                for (const match of getMatches(message, regex)) {
                    const range = {
                        start: match.index,
                        end: match.index + match[0].length
                    };

                    addMatch(
                        regex,
                        match[0],
                        this.normalize(match[0])[0],
                        range
                    );
                }

                for (const variant of normalizedVariants) {
                    for (const match of getMatches(variant, regex)) {
                        const range = findOriginalRange(message, match[0]);

                        if (!range) {
                            continue;
                        }

                        addMatch(
                            regex,
                            message.slice(range.start, range.end),
                            match[0],
                            range
                        );
                    }
                }
            } else {
                for (const variant of normalizedVariants) {
                    for (const match of getMatches(variant, regex)) {
                        const range = findOriginalRange(message, match[0]);

                        if (!range) {
                            continue;
                        }

                        addMatch(
                            regex,
                            message.slice(range.start, range.end),
                            match[0],
                            range
                        );
                    }
                }

                if (!this.ignore?.reversed) {
                    for (const variant of normalizedVariants) {
                        const reversedMessage = this.reverse(variant);

                        for (const match of getMatches(reversedMessage, regex)) {
                            const reversedStart = match.index;
                            const reversedEnd = reversedStart + match[0].length;

                            const start = variant.length - reversedEnd;
                            const end = variant.length - reversedStart;

                            const reversedMatch = variant.slice(start, end);
                            const range = findOriginalRange(message, reversedMatch);

                            if (!range) continue;

                            addMatch(
                                regex,
                                message.slice(range.start, range.end),
                                reversedMatch,
                                range
                            );
                        }
                    }
                }

                for (const match of getMatches(message, regex)) {
                    const range = {
                        start: match.index,
                        end: match.index + match[0].length
                    };

                    addMatch(
                        regex,
                        match[0],
                        this.normalize(match[0])[0],
                        range
                    );
                }
            }
        }

        return matches;
    }
}
