export const regexes = {
    // General
    email: /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/,
    url: /^https?:\/\/[^\s/$.?#].[^\s]*$/i,
    tel: /^\+?[0-9\s\-().]{7,20}$/,

    // Numbers
    number: /^-?\d+(\.\d+)?$/,
    integer: /^-?\d+$/,
    decimal: /^\d*\.\d+$/,
    positiveNumber: /^\d+(\.\d+)?$/,
    negativeNumber: /^-\d+(\.\d+)?$/,

    // Text
    alphanumeric: /^[a-z0-9]+$/i,
    alphanumericSpace: /^[a-z0-9 ]+$/i,
    username: /^[a-z0-9._-]{3,24}$/i,
    slug: /^[a-z0-9]+(?:-[a-z0-9]+)*$/,

    // Passwords
    password: /^.{8,}$/,
    passwordModerate: /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d).{8,}$/,
    passwordStrong: /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[!@#$%^&*()_+\-=[\]{};':"\\|,.<>/?`~]).{8,}$/,

    // Network
    ipv4: /^(?:(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)\.){3}(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)$/,
    ipv6: /^(?:(?:[a-f\d]{1,4}:){7}[a-f\d]{1,4}|(?:[a-f\d]{1,4}:){1,7}:|(?:[a-f\d]{1,4}:){1,6}:[a-f\d]{1,4}|(?:[a-f\d]{1,4}:){1,5}(?::[a-f\d]{1,4}){1,2}|(?:[a-f\d]{1,4}:){1,4}(?::[a-f\d]{1,4}){1,3}|(?:[a-f\d]{1,4}:){1,3}(?::[a-f\d]{1,4}){1,4}|(?:[a-f\d]{1,4}:){1,2}(?::[a-f\d]{1,4}){1,5}|[a-f\d]{1,4}:(?:(?::[a-f\d]{1,4}){1,6})|:(?:(?::[a-f\d]{1,4}){1,7}|:))$/i,
    
    // Dates
    dateISO: /^(?:[12]\d{3})-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01])$/,

    // Time
    time12: /^(0?[1-9]|1[0-2]):[0-5]\d$/,
    time12Meridiem: /^(0?[1-9]|1[0-2]):[0-5]\d\s?(AM|PM)$/i,
    time24: /^([01]\d|2[0-3]):[0-5]\d$/,
    time24Seconds: /^([01]\d|2[0-3]):[0-5]\d:[0-5]\d$/,

    // Files
    fileName: /^[\w,\s-]+\.[a-zA-Z0-9]+$/,
} as const;
